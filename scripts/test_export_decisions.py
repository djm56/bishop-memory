class EndToEnd(unittest.TestCase):
    """export_directives against a temp memory root and a stubbed service."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = os.path.join(self.tmp.name, "memory")
        os.makedirs(os.path.join(self.root, "reference"))
        self.path = os.path.join(self.root, "reference", "DIRECTIVES.md")
        with open(self.path, "w", encoding="utf-8") as fh:
            fh.write(BASE)

    def read(self):
        with open(self.path, encoding="utf-8") as fh:
            return fh.read()

    def export(self, proposals, dry_run=False):
        def fake_api(method, url, payload=None, timeout=30):
            assert method == "GET" and url.startswith("http://svc"), url
            if "state=accepted" in url:
                return 200, {"directive_proposals": [p for p in proposals if p["state"] == "accepted"]}
            if "state=declined" in url:
                return 200, {"directive_proposals": [p for p in proposals if p["state"] == "declined"]}
            if "/v1/findings" in url:
                return 200, {"findings": [{"id": 1, "finding_date": "2026-10-13", "target": "new target"}]}
            raise AssertionError(url)

        with mock.patch.object(ed.tc, "api", fake_api):
            return ed.export_directives("http://svc", "h", self.root, dry_run)

    def backups(self):
        d = os.path.join(self.root, "workspace", "triage-backups")
        return sorted(os.listdir(d)) if os.path.isdir(d) else []

    def test_write_then_second_run_writes_nothing(self):
        proposals = [prop("DIR-004", "declined"), prop("DIR-007", "accepted")]
        self.assertEqual(self.export(proposals), (0, 2))
        written = self.read()
        self.assertEqual(written, swap(swap(EXPECTED_RETIRE_004, "## Retired Entries", ENTRY_007 + "\n## Retired Entries"),
                                       ROW_006 + "\n", ROW_006 + "\n" + ROW_007 + "\n"))
        self.assertEqual(len(self.backups()), 1)
        self.assertEqual(self.export(proposals), (0, 0))
        self.assertEqual(self.read(), written)
        self.assertEqual(len(self.backups()), 1)

    def test_dry_run_writes_nothing(self):
        self.assertEqual(self.export([prop("DIR-004", "declined")], dry_run=True), (0, 1))
        self.assertEqual(self.read(), BASE)
        self.assertEqual(self.backups(), [])

    def test_conflict_alone_exits_three_and_modifies_nothing(self):
        self.assertEqual(self.export([prop("DIR-001", "accepted", rule="Different.")]), (3, 0))
        self.assertEqual(self.read(), BASE)

    def test_conflict_plus_other_change_still_exits_three_after_writing(self):
        code, changes = self.export([prop("DIR-001", "accepted", rule="Different."), prop("DIR-004", "declined")])
        self.assertEqual((code, changes), (3, 1))
        self.assertEqual(self.read(), EXPECTED_RETIRE_004)

    def test_over_budget_exits_one_and_writes_nothing(self):
        self.assertEqual(self.export([prop("DIR-007", "accepted", rule="x" * 1600)]), (1, 0))
        self.assertEqual(self.read(), BASE)
        self.assertEqual(self.backups(), [])

    def test_guard_refusal_exits_one_and_writes_nothing(self):
        def greedy(text, kind, did):
            return ed.remove_rows.__wrapped__(text, kind, did).replace(ROW_001 + "\n", "")

        real = ed.remove_rows
        greedy.__wrapped__ = real
        with mock.patch.object(ed, "remove_rows", greedy):
            self.assertEqual(self.export([prop("DIR-004", "declined")]), (1, 0))
        self.assertEqual(self.read(), BASE)
        self.assertEqual(self.backups(), [])

    def test_missing_file_exits_two(self):
        os.remove(self.path)
        self.assertEqual(self.export([prop("DIR-004", "declined")]), (2, 0))

    def test_hand_extended_entry_exits_one_and_leaves_the_file_unchanged(self):
        added = "- **Added:** 2026-10-01 · **Source:** bishop-memory triage · **Evidence:** [2026-10-01] — input validation sites\n"
        bad = swap(BASE, added, added + "```\n# x\n```\n")
        with open(self.path, "w", encoding="utf-8") as fh:
            fh.write(bad)
        self.assertEqual(self.export([prop("DIR-002", "accepted", rule="Changed rule.")]), (1, 0))
        self.assertEqual(self.read(), bad)
        self.assertEqual(self.backups(), [])

    def test_reaccept_output_shows_the_removed_retired_row(self):
        hand = "| DIR-005 | Log structured events | deprecated | DIR-009 (hand-written) |"
        with open(self.path, "w", encoding="utf-8") as fh:
            fh.write(swap(BASE, RET_005, hand))
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(self.export([prop("DIR-005", "accepted")], dry_run=True), (0, 1))
        self.assertIn("-" + hand, out.getvalue())

    def test_missing_retired_row_note_is_printed(self):
        with open(self.path, "w", encoding="utf-8") as fh:
            fh.write(swap(BASE, RET_005 + "\n", ""))
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            self.assertEqual(self.export([prop("DIR-005", "declined")]), (0, 0))
        self.assertIn("DIR-005: already deprecated but has no Retired Entries row", out.getvalue())

    def test_evidence_fetch_failure_exits_one_and_writes_nothing(self):
        def failing_api(method, url, payload=None, timeout=30):
            if "state=accepted" in url:
                return 200, {"directive_proposals": [prop("DIR-007", "accepted")]}
            if "state=declined" in url:
                return 200, {"directive_proposals": []}
            raise urllib.error.URLError("connection refused")

        for exc in (urllib.error.URLError("connection refused"),
                    urllib.error.HTTPError("http://svc", 500, "boom", None, None)):
            def api(method, url, payload=None, timeout=30, exc=exc):
                if "/v1/findings" in url:
                    raise exc
                return failing_api(method, url, payload, timeout)
            err = io.StringIO()
            with mock.patch.object(ed.tc, "api", api), contextlib.redirect_stderr(err):
                self.assertEqual(ed.export_directives("http://svc", "h", self.root, False), (1, 0))
            self.assertIn("could not fetch evidence", err.getvalue())
            self.assertEqual(self.read(), BASE)
            self.assertEqual(self.backups(), [])


