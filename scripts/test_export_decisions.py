    def test_over_budget_entry_is_refused(self):
        with self.assertRaises(ed.DirectiveError):
            run(BASE, [prop("DIR-007", "accepted", rule="x" * 1600)])
        with self.assertRaises(ed.DirectiveError):
            run(BASE, [prop("DIR-002", "accepted", rule="x" * 1600)])

