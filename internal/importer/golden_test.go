// Package importer — golden test for the importer's database output.
//
// TestGoldenImportState imports the shipped fixture (testdata/memory) through
// importer.SyncHarnessStats into a fresh database, dumps every table (the FTS5
// index included) as deterministic text, and compares that text byte-for-byte
// with testdata/golden/importer-state.golden.
//
// Scope, so nobody reads more into it than it checks: the test calls
// SyncHarnessStats directly. It does not go through POST /v1/documents/sync,
// and it does not run SyncAgents, which that handler also calls for a
// registered harness.
//
// Normalisation, the only edits made to the raw output:
//   - A column whose schema default is CURRENT_TIMESTAMP (read from
//     PRAGMA table_info) is written as <CURRENT_TIMESTAMP>. Those values are
//     wall-clock and differ on every run.
//   - The fixture's absolute path (the symlink-resolved root the importer
//     stores in source_path) is written as <FIXTURE>, so the golden holds on
//     any checkout.
//   - Row ids are not normalised. The database is fresh and the walk order is
//     lexical, so ids repeat exactly across runs, and a change in id assignment
//     is a real change the golden should show.
//
// Updating the golden after an intended change:
//
//	UPDATE_GOLDEN=1 go test ./internal/importer -run TestGoldenImportState -count=1
//
// An update run writes the golden and then fails the test on purpose, so an
// update run is never green. Run again without UPDATE_GOLDEN to confirm. CI
// sets UPDATE_GOLDEN to the empty string (.github/workflows/ci.yml), so update
// mode never runs in CI. The test itself fails whenever the variable is
// non-empty, so a stray value cannot turn the gate into a pass.
//
// The golden is the gate in docs/plans/HARNESS-PORTABILITY-PLAN.md §8: an
// importer change merges only when this output is identical, or the difference
// is an intended fix that ships its own test.
package importer

import (
	"database/sql"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
)

const (
	// goldenFixtureRel is the fixture root relative to this package directory.
	goldenFixtureRel = "../../testdata/memory"
	// goldenFile is the checked-in expected output, relative to this package.
	goldenFile = "../../testdata/golden/importer-state.golden"
	// goldenHarness is the harness name the fixture is imported under. It is
	// stored in documents.harness, so it appears in the golden.
	goldenHarness = "fixture"
)

// TestGoldenImportState compares the database state after importing the
// fixture against the checked-in golden. See the package docblock for what is
// normalised and how to regenerate.
func TestGoldenImportState(t *testing.T) {
	db := openTestDB(t)

	stats, err := SyncHarnessStats(db, goldenFixtureRel, goldenHarness)
	if err != nil {
		t.Fatalf("SyncHarnessStats(%s): %v", goldenFixtureRel, err)
	}

	dump, err := dumpDatabase(db)
	if err != nil {
		t.Fatalf("dump database: %v", err)
	}

	// The importer stores the symlink-resolved root, so both forms are
	// replaced: the resolved one first, then the plain absolute one.
	abs, err := filepath.Abs(goldenFixtureRel)
	if err != nil {
		t.Fatalf("abs fixture root: %v", err)
	}
	resolved, err := filepath.EvalSymlinks(abs)
	if err != nil {
		t.Fatalf("resolve fixture root: %v", err)
	}

	var b strings.Builder
	b.WriteString("# importer golden — generated by TestGoldenImportState\n")
	b.WriteString("# regenerate: UPDATE_GOLDEN=1 go test ./internal/importer -run TestGoldenImportState -count=1\n")
	fmt.Fprintf(&b, "# harness: %s\n", goldenHarness)
	// %+v prints each field by name, so the golden is tied to the field names
	// of SyncHarnessStats on purpose: renaming a field changes this line and
	// fails the golden, which is the intended signal.
	fmt.Fprintf(&b, "# stats: %+v\n", stats)
	b.WriteString(dump)
	got := strings.ReplaceAll(b.String(), resolved, "<FIXTURE>")
	got = strings.ReplaceAll(got, abs, "<FIXTURE>")

	if os.Getenv("UPDATE_GOLDEN") != "" {
		if err := os.MkdirAll(filepath.Dir(goldenFile), 0o755); err != nil {
			t.Fatalf("mkdir golden dir: %v", err)
		}
		if err := os.WriteFile(goldenFile, []byte(got), 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		// Fail on purpose: an update run must never be green.
		t.Fatalf("UPDATE_GOLDEN set: wrote %s. Unset UPDATE_GOLDEN and re-run to confirm.", goldenFile)
	}

	want, err := os.ReadFile(goldenFile)
	if err != nil {
		t.Fatalf("read golden %s: %v (create it with UPDATE_GOLDEN=1)", goldenFile, err)
	}
	if got != string(want) {
		t.Fatalf("import state differs from %s; first difference at %s",
			goldenFile, firstLineDiff(got, string(want)))
	}
}

// dumpDatabase renders every user table in db, the FTS5 virtual table
// included, in name order. FTS5 shadow tables (documents_fts_*) are skipped
// because the virtual table they back already covers them.
func dumpDatabase(db *sql.DB) (string, error) {
	names, err := queryStrings(db, `
		SELECT name FROM sqlite_master
		 WHERE type = 'table'
		   AND name NOT LIKE 'sqlite\_%' ESCAPE '\'
		   AND name NOT LIKE 'documents\_fts\_%' ESCAPE '\'
		 ORDER BY name`)
	if err != nil {
		return "", fmt.Errorf("list tables: %w", err)
	}

	var b strings.Builder
	for _, name := range names {
		section, err := dumpTable(db, name)
		if err != nil {
			return "", fmt.Errorf("dump %s: %w", name, err)
		}
		b.WriteString(section)
	}
	return b.String(), nil
}

// dumpTable renders one table: a header, then each row keyed by rowid with one
// line per column. Ordering is by rowid, so the output does not depend on the
// order SQLite happens to return rows in.
func dumpTable(db *sql.DB, name string) (string, error) {
	timestamps, err := timestampColumns(db, name)
	if err != nil {
		return "", err
	}

	rows, err := db.Query(`SELECT rowid, * FROM "` + name + `" ORDER BY rowid`)
	if err != nil {
		return "", err
	}
	defer rows.Close()

	cols, err := rows.Columns()
	if err != nil {
		return "", err
	}

	var b strings.Builder
	fmt.Fprintf(&b, "[%s]\n", name)
	for rows.Next() {
		vals := make([]any, len(cols))
		ptrs := make([]any, len(cols))
		for i := range vals {
			ptrs[i] = &vals[i]
		}
		if err := rows.Scan(ptrs...); err != nil {
			return "", err
		}
		// cols[0] is the rowid alias selected above; the rest are the table's columns.
		fmt.Fprintf(&b, "  row %s=%s\n", cols[0], renderValue(vals[0], false))
		for i := 1; i < len(cols); i++ {
			fmt.Fprintf(&b, "    %s = %s\n", cols[i], renderValue(vals[i], timestamps[cols[i]]))
		}
	}
	if err := rows.Err(); err != nil {
		return "", err
	}
	return b.String(), nil
}

// timestampColumns returns the names of name's columns whose schema default is
// CURRENT_TIMESTAMP. Their stored values are wall-clock, so the dump
// normalises them.
func timestampColumns(db *sql.DB, name string) (map[string]bool, error) {
	rows, err := db.Query(`PRAGMA table_info("` + name + `")`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	out := map[string]bool{}
	for rows.Next() {
		var (
			cid     int
			colName string
			colType string
			notNull int
			dflt    sql.NullString
			pk      int
		)
		if err := rows.Scan(&cid, &colName, &colType, &notNull, &dflt, &pk); err != nil {
			return nil, err
		}
		if dflt.Valid && strings.Contains(dflt.String, "CURRENT_TIMESTAMP") {
			out[colName] = true
		}
	}
	return out, rows.Err()
}

// queryStrings runs a single-column query and returns its values in order.
func queryStrings(db *sql.DB, query string) ([]string, error) {
	rows, err := db.Query(query)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var out []string
	for rows.Next() {
		var s string
		if err := rows.Scan(&s); err != nil {
			return nil, err
		}
		out = append(out, s)
	}
	return out, rows.Err()
}

// renderValue formats one scanned SQLite value for the dump. Text and blobs are
// Go-quoted so embedded newlines stay on one line. A timestamp-normalised
// value that is not NULL renders as <CURRENT_TIMESTAMP>.
func renderValue(v any, timestamp bool) string {
	if v == nil {
		return "NULL"
	}
	if timestamp {
		return "<CURRENT_TIMESTAMP>"
	}
	switch x := v.(type) {
	case int64:
		return strconv.FormatInt(x, 10)
	case float64:
		return strconv.FormatFloat(x, 'g', -1, 64)
	case []byte:
		return strconv.Quote(string(x))
	case string:
		return strconv.Quote(x)
	default:
		return fmt.Sprintf("<unexpected %T>", x)
	}
}

// firstLineDiff names the first line where got and want disagree, for the
// failure message.
func firstLineDiff(got, want string) string {
	g := strings.Split(got, "\n")
	w := strings.Split(want, "\n")
	for i := 0; i < len(g) || i < len(w); i++ {
		var gl, wl string
		if i < len(g) {
			gl = g[i]
		}
		if i < len(w) {
			wl = w[i]
		}
		if gl != wl {
			return fmt.Sprintf("line %d\n  want: %s\n  got:  %s", i+1, wl, gl)
		}
	}
	return "no line difference (trailing bytes differ)"
}
